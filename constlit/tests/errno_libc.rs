//! Static checks that `errno!`'s per-target numbers match libc's. They run on the
//! host and, with `cargo check --tests --target …`, on other Linux targets.
#![cfg(any(target_os = "linux", target_os = "android"))]

use constlit::linux::__errnos as table;

/// One `const` assertion per errno: `table::NAME == libc::NAME`.
macro_rules! same {
    ($($name:ident)*) => {
        $(
            const _: () = assert!(table::$name == libc::$name);
        )*
    };
}

same! {
        EPERM ENOENT ESRCH EINTR EIO ENXIO E2BIG ENOEXEC
        EBADF ECHILD EAGAIN ENOMEM EACCES EFAULT ENOTBLK EBUSY
        EEXIST EXDEV ENODEV ENOTDIR EISDIR EINVAL ENFILE EMFILE
        ENOTTY ETXTBSY EFBIG ENOSPC ESPIPE EROFS EMLINK EPIPE
        EDOM ERANGE EDEADLK EDEADLOCK ENAMETOOLONG ENOLCK ENOSYS ENOTEMPTY
        ELOOP ENOMSG EIDRM ECHRNG EL2NSYNC EL3HLT EL3RST ELNRNG
        EUNATCH ENOCSI EL2HLT EBADE EBADR EXFULL ENOANO EBADRQC
        EBADSLT EBFONT ENOSTR ENODATA ETIME ENOSR ENONET ENOPKG
        EREMOTE ENOLINK EADV ESRMNT ECOMM EPROTO EMULTIHOP EDOTDOT
        EBADMSG EOVERFLOW ENOTUNIQ EBADFD EREMCHG ELIBACC ELIBBAD ELIBSCN
        ELIBMAX ELIBEXEC EILSEQ ERESTART ESTRPIPE EUSERS ENOTSOCK EDESTADDRREQ
        EMSGSIZE EPROTOTYPE ENOPROTOOPT EPROTONOSUPPORT ESOCKTNOSUPPORT EOPNOTSUPP EPFNOSUPPORT EAFNOSUPPORT
        EADDRINUSE EADDRNOTAVAIL ENETDOWN ENETUNREACH ENETRESET ECONNABORTED ECONNRESET ENOBUFS
        EISCONN ENOTCONN ESHUTDOWN ETOOMANYREFS ETIMEDOUT ECONNREFUSED EHOSTDOWN EHOSTUNREACH
        EALREADY EINPROGRESS ESTALE EUCLEAN ENOTNAM ENAVAIL EISNAM EREMOTEIO
        EDQUOT ENOMEDIUM EMEDIUMTYPE ECANCELED ENOKEY EKEYEXPIRED EKEYREVOKED EKEYREJECTED
        EOWNERDEAD ENOTRECOVERABLE ERFKILL EHWPOISON
}

const _: () = assert!(table::SUPPORTED);
